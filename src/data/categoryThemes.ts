export function getCategoryTheme(categoryName: string): CategoryTheme {
  const key = categoryName.toLowerCase();
  if (CATEGORY_THEMES[key]) {
    return CATEGORY_THEMES[key];
  }
  // Default fallback for custom user-created categories
  return {
    id: categoryName,
    name: categoryName,
    bannerTitle: categoryName.toUpperCase(),
    bannerBg: 'bg-neutral-900',
    bannerBgHex: '#171717',
    bannerText: 'text-white',
    subnavBg: 'bg-neutral-900',
    subnavText: 'text-white',
    subnavActiveBorder: 'border-white',
    secondaryBarBg: 'bg-black',
    secondaryBarText: 'text-white',
    secondaryActiveIndicator: 'border-white text-white',
    tagColor: 'text-neutral-700',
    tagColorHex: '#404040',
    badgeBg: 'bg-black text-white',
    accentBorder: 'border-black',
    liveCircleBorder: 'border-red-600 text-red-600',
    quickLinks: [{ label: 'Home' }, { label: categoryName }],
    secondaryLinks: [{ label: `${categoryName} Desk >` }],
    newsletterInfo: {
      title: `${categoryName} Digest`,
      cadence: 'Weekly dispatch',
      description: `Stay ahead with curated reports and top dispatches filed to the ${categoryName} news desk.`,
      cardBg: 'bg-neutral-800',
    },
  };
}
